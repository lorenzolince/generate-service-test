CREATE TABLE GS_PERSONA
(
    ID_PERSONA       NUMBER(10) NOT NULL,
    NOMBRE           VARCHAR2(100) NOT NULL,
    APELLIDO         VARCHAR2(100) NOT NULL,
    EDAD             NUMBER(10) NULL,
    EMAIL            VARCHAR2(150) NULL,
    FECHA_NACIMIENTO DATE NULL,
    ACTIVO           NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_REGISTRO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_GS_PERSONA PRIMARY KEY (ID_PERSONA),
    CONSTRAINT CK_GS_PERSONA_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE SEQUENCE GS_PERSONA_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE TRIGGER BI_GS_PERSONA
BEFORE INSERT ON GS_PERSONA
FOR EACH ROW
BEGIN
    IF :NEW.ID_PERSONA IS NULL THEN
        SELECT GS_PERSONA_SEQ.NEXTVAL
          INTO :NEW.ID_PERSONA
          FROM DUAL;
    END IF;
END;
