    P_NUMEROS    IN GS_NUMBER_TAB,
    P_TEXTOS     IN OUT GS_VARCHAR2_TAB,
    P_FECHAS     OUT GS_DATE_TAB,
    P_TIMESTAMPS OUT GS_TIMESTAMP_TAB,
    P_TOTAL      OUT NUMBER,
    P_SUMA       OUT NUMBER
)
AS
BEGIN
    P_TOTAL := 0;
    P_SUMA := 0;

    IF P_NUMEROS IS NOT NULL THEN
        P_TOTAL := P_TOTAL + P_NUMEROS.COUNT;

        FOR I IN 1 .. P_NUMEROS.COUNT LOOP
            IF P_NUMEROS(I) IS NOT NULL THEN
                P_SUMA := P_SUMA + P_NUMEROS(I);
            END IF;
        END LOOP;
    END IF;

    IF P_TEXTOS IS NULL THEN
        P_TEXTOS := GS_VARCHAR2_TAB();
    END IF;

    P_TOTAL := P_TOTAL + P_TEXTOS.COUNT;
    P_TEXTOS.EXTEND;
    P_TEXTOS(P_TEXTOS.COUNT) := 'AGREGADO_ORACLE';

    P_FECHAS := GS_DATE_TAB(DATE '1991-02-18', TRUNC(SYSDATE));
    P_TIMESTAMPS := GS_TIMESTAMP_TAB
    (
        CAST(SYSTIMESTAMP AS TIMESTAMP),
