CREATE OR REPLACE PROCEDURE GS_SP_GET_PERSONA
(
    P_ID_PERSONA IN NUMBER,
    P_PERSONA    OUT GS_PERSONA_OBJ
)
AS
BEGIN
    SELECT GS_PERSONA_OBJ
    (
        P.ID_PERSONA,
        P.NOMBRE,
        P.APELLIDO,
        P.EDAD,
        P.EMAIL,
        P.FECHA_NACIMIENTO,
        P.ACTIVO,
        P.FECHA_REGISTRO
    )
      INTO P_PERSONA
      FROM GS_PERSONA P
     WHERE P.ID_PERSONA = P_ID_PERSONA;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        P_PERSONA := NULL;
END;
/

CREATE OR REPLACE PROCEDURE GS_SP_GET_PERSONAS
(
    P_PERSONAS OUT GS_PERSONA_TAB
)
AS
BEGIN
    SELECT GS_PERSONA_OBJ
    (
        P.ID_PERSONA,
        P.NOMBRE,
        P.APELLIDO,
        P.EDAD,
        P.EMAIL,
        P.FECHA_NACIMIENTO,
