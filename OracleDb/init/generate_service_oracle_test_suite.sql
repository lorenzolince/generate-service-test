END;
/

CREATE OR REPLACE PROCEDURE GS_SP_INSERT_PERSONA
(
    P_PERSONA    IN GS_PERSONA_OBJ,
    P_ID_PERSONA OUT NUMBER
)
AS
BEGIN
    IF P_PERSONA IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'P_PERSONA no puede ser null');
    END IF;

    INSERT INTO GS_PERSONA
    (
        NOMBRE,
        APELLIDO,
        EDAD,
        EMAIL,
        FECHA_NACIMIENTO,
        ACTIVO
    )
    VALUES
    (
        P_PERSONA.NOMBRE,
        P_PERSONA.APELLIDO,
        P_PERSONA.EDAD,
        P_PERSONA.EMAIL,
        P_PERSONA.FECHA_NACIMIENTO,
        NVL(P_PERSONA.ACTIVO, 1)
    )
    RETURNING ID_PERSONA INTO P_ID_PERSONA;
END;
/

CREATE OR REPLACE PROCEDURE GS_SP_UPDATE_PERSONA
(
    P_PERSONA     IN GS_PERSONA_OBJ,
    P_ACTUALIZADO OUT NUMBER
)
AS
BEGIN
    IF P_PERSONA IS NULL THEN
        P_ACTUALIZADO := 0;
        RETURN;
    END IF;

    UPDATE GS_PERSONA
       SET NOMBRE = P_PERSONA.NOMBRE,
           APELLIDO = P_PERSONA.APELLIDO,
           EDAD = P_PERSONA.EDAD,
           EMAIL = P_PERSONA.EMAIL,
           FECHA_NACIMIENTO = P_PERSONA.FECHA_NACIMIENTO,
           ACTIVO = NVL(P_PERSONA.ACTIVO, 1)
     WHERE ID_PERSONA = P_PERSONA.ID_PERSONA;

    P_ACTUALIZADO := CASE WHEN SQL%ROWCOUNT > 0 THEN 1 ELSE 0 END;
END;
/

CREATE OR REPLACE PROCEDURE GS_SP_DELETE_PERSONA
(
    P_ID_PERSONA IN NUMBER,
    P_ELIMINADO  OUT NUMBER
)
AS
BEGIN
    DELETE FROM GS_PERSONA
     WHERE ID_PERSONA = P_ID_PERSONA;

    P_ELIMINADO := CASE WHEN SQL%ROWCOUNT > 0 THEN 1 ELSE 0 END;
END;
/

CREATE OR REPLACE PROCEDURE GS_SP_GET_PERSONA_DETALLE
(
    P_ID_PERSONA IN NUMBER,
    P_PERSONA    OUT GS_PERSONA_DETALLE_OBJ
)
AS
BEGIN
    SELECT GS_PERSONA_DETALLE_OBJ
    (
        P.ID_PERSONA,
        P.NOMBRE,
        P.APELLIDO,
        P.EDAD,
        P.EMAIL,
        P.FECHA_NACIMIENTO,
        P.ACTIVO,
        P.FECHA_REGISTRO,
        (
            SELECT GS_DIRECCION_OBJ
            (
                D.PAIS,
                D.CIUDAD,
                D.TELEFONO
            )
              FROM GS_PERSONA_DIRECCION D
             WHERE D.ID_PERSONA = P.ID_PERSONA
        ),
        CAST
        (
            MULTISET
            (
                SELECT GS_HIJO_OBJ
                (
                    H.NOMBRE,
                    H.APELLIDO,
                    H.FECHA_NACIMIENTO,
                    (
                        SELECT GS_DIRECCION_OBJ
                        (
                            HD.PAIS,
                            HD.CIUDAD,
                            HD.TELEFONO
                        )
                          FROM GS_HIJO_DIRECCION HD
                         WHERE HD.ID_HIJO = H.ID_HIJO
                    )
                )
                  FROM GS_HIJO H
                 WHERE H.ID_PERSONA = P.ID_PERSONA
            )
            AS GS_HIJO_TAB
        )
    )
      INTO P_PERSONA
      FROM GS_PERSONA P
     WHERE P.ID_PERSONA = P_ID_PERSONA;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        P_PERSONA := NULL;
END;
/

